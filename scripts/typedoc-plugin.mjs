/**
 * Local TypeDoc plugin (typedoc.json "plugin"):
 *
 * - Project documents are grouped by their folder, with the group names of
 *   scripts/doc-structure.mjs: docs/tutorials → "Tutorials", docs/how-to →
 *   "How-to", docs/reference → "Reference", docs/explanation →
 *   "Explanation", docs/guidelines → "Guidelines", docs/examples →
 *   "Examples", docs/upgrading → "Upgrading". A page needs no `group` front
 *   matter (and the structure check does not allow one).
 * - Within a group, the pages follow the order of scripts/doc-structure.mjs
 *   (the index first), not the order of their file names.
 * - The two entry points (`@vestra-player/sdk`, `@vestra-player/sdk/testing`)
 *   are listed under "API" instead of "Modules".
 * - The hidden setup lines of `@example` code blocks (above `// ---cut---`,
 *   scripts/doc-standard.mjs) are removed: they are type checked, not shown.
 * - llms.txt (generated by scripts/llms.mjs) is copied to
 *   the site's root.
 * - Each old address of `REDIRECTS` (scripts/doc-structure.mjs) gets a page
 *   that redirects to its new address, so links from outside keep working.
 * - Diagrams: a ```mermaid block (typedoc.json `ignoredHighlightLanguages`)
 *   is drawn in the browser by Mermaid, loaded from a pinned version
 *   (`MERMAID`) only on pages that have one. Diagrams are Mermaid, with
 *   every edge written out, so that the documentation tree for agents
 *   (scripts/docs-tree.mjs) carries the same source a
 *   language model can read.
 */
import { copyFileSync, existsSync, mkdirSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { Converter, JSX, RendererEvent } from "typedoc";
import { GROUPS, REDIRECTS } from "./doc-structure.mjs";
import { CUT, withoutHidden } from "./doc-standard.mjs";

const root = resolve(import.meta.dirname, "..");

/** The Mermaid build the site loads (pinned; an ES module). */
export const MERMAID =
  "https://cdn.jsdelivr.net/npm/mermaid@11.4.1/dist/mermaid.esm.min.mjs";

/**
 * Runs in the page: each `<pre><code class="mermaid">` that TypeDoc wrote
 * becomes a `<div class="mermaid">` with the same source, which Mermaid
 * draws in the site's light or dark theme.
 */
const MERMAID_SCRIPT = `
const blocks = [...document.querySelectorAll("pre > code.mermaid")];
if (blocks.length) {
  const { default: mermaid } = await import(${JSON.stringify(MERMAID)});
  const theme = document.documentElement.dataset.theme;
  const dark = theme === "dark" || (theme !== "light" && matchMedia("(prefers-color-scheme: dark)").matches);
  mermaid.initialize({ startOnLoad: false, securityLevel: "strict", theme: dark ? "dark" : "default" });
  for (const code of blocks) {
    const diagram = document.createElement("div");
    diagram.className = "mermaid";
    diagram.textContent = code.textContent;
    code.parentElement.replaceWith(diagram);
  }
  await mermaid.run({ querySelector: "div.mermaid" });
}
`;

/** Folder under docs/ → group title. */
const TITLES = Object.fromEntries(GROUPS.map((g) => [g.folder, g.title]));
/** "folder/file.md" → position in the navigation. */
const ORDER = new Map(
  GROUPS.flatMap((g) => g.pages.map((p) => `${g.folder}/${p.file}`)).map(
    (key, index) => [key, index],
  ),
);

/** The "folder/file.md" of a project document, or undefined. */
function pageKey(document) {
  const path = document.project.files.getReflectionPath(document) ?? "";
  return /\/docs\/([^/]+\/[^/]+\.md)$/.exec(path)?.[1];
}

/** @param {import("typedoc").Application} app */
export function load(app) {
  app.internationalization.addTranslations("en", {
    kind_plural_module: "API",
  });
  // After {@includeCode} has been resolved (when the reflections were
  // created).
  app.converter.on(Converter.EVENT_RESOLVE_BEGIN, (context) => {
    for (const reflection of Object.values(context.project.reflections))
      for (const block of reflection.comment?.blockTags ?? [])
        if (block.tag === "@example")
          for (const part of block.content)
            if (part.kind === "code" && part.text.includes(CUT))
              part.text = withoutHidden(part.text);
  });
  app.converter.on(Converter.EVENT_CREATE_DOCUMENT, (_context, document) => {
    if ("group" in document.frontmatter) return;
    const folder = pageKey(document)?.split("/")[0];
    if (folder && TITLES[folder]) document.frontmatter.group = TITLES[folder];
  });
  // After TypeDoc's GroupPlugin (priority -100) has built and sorted the
  // groups.
  app.converter.on(
    Converter.EVENT_RESOLVE_END,
    (context) => {
      const position = (reflection) =>
        reflection.isDocument()
          ? (ORDER.get(pageKey(reflection)) ?? Infinity)
          : Infinity;
      for (const group of context.project.groups ?? [])
        if (Object.values(TITLES).includes(group.title))
          group.children.sort((a, b) => position(a) - position(b));
    },
    -200,
  );
  app.renderer.hooks.on("body.end", () =>
    JSX.createElement(
      "script",
      { type: "module" },
      JSX.createElement(JSX.Raw, { html: MERMAID_SCRIPT }),
    ),
  );
  app.renderer.on(RendererEvent.END, (event) => {
    copyFileSync(
      join(root, "llms.txt"),
      join(event.outputDirectory, "llms.txt"),
    );
    for (const [from, to] of Object.entries(REDIRECTS)) {
      const file = join(event.outputDirectory, from);
      if (existsSync(file))
        throw new Error(`REDIRECTS: ${from} is a page of the site again`);
      const target = relative(dirname(file), join(event.outputDirectory, to))
        .split("\\")
        .join("/");
      mkdirSync(dirname(file), { recursive: true });
      writeFileSync(
        file,
        `<!doctype html>
<meta charset="utf-8">
<title>Moved</title>
<link rel="canonical" href="${target}">
<meta http-equiv="refresh" content="0; url=${target}">
<p>This page moved to <a href="${target}">${target}</a>.</p>
`,
      );
    }
  });
}
